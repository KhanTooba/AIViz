/** Source emitted by the workspace-domain creation command. It is deliberately
 * conservative: authors can replace the arithmetic with more precise transfer
 * functions while the generated lattice is immediately loadable and valid. */
export function domainModuleTemplate(id: string, name: string): string {
  return `// Generated by AIViz. Replace conservative operations with your domain semantics.
const BOT = 0;
const ZERO = 1;
const NONZERO = 2;
const TOP = ZERO | NONZERO;

export const lattice = {
  id: ${JSON.stringify(id)},
  name: ${JSON.stringify(name)},
  finiteLattice: true,
  bottom: BOT,
  top: TOP,
  isBottom: (value) => value === BOT,
  isTop: (value) => value === TOP,
  equal: (left, right) => left === right,
  leq: (left, right) => (left & ~right) === 0,
  join: (left, right) => left | right,
  meet: (left, right) => left & right,
  widen: (left, right) => left | right,
  narrow: (left, right) => left & right,
  constant: (value) => (value === 0 ? ZERO : NONZERO),
  add: (_left, _right) => TOP,
  sub: (_left, _right) => TOP,
  mul: (_left, _right) => TOP,
  div: (_left, _right) => TOP,
  mod: (_left, _right) => TOP,
  neg: (value) => value,
  refine: (_operator, left, _right) => left,
  format: (value) =>
    value === BOT
      ? { repr: '⊥', kind: 'bottom' }
      : value === TOP
        ? { repr: '⊤', kind: 'top' }
        : { repr: value === ZERO ? '0' : '≠0', kind: 'value' },
  describeLoss: () => undefined,
  latticeGraph: () => ({
    nodes: [
      { id: 'bottom', label: '⊥' },
      { id: 'zero', label: '0' },
      { id: 'nonzero', label: '≠0' },
      { id: 'top', label: '⊤' },
    ],
    edges: [
      ['bottom', 'zero'],
      ['bottom', 'nonzero'],
      ['zero', 'top'],
      ['nonzero', 'top'],
    ],
  }),
};
`;
}

export function domainManifestTemplate(id: string, name: string): string {
  return `${JSON.stringify(
    {
      schemaVersion: 1,
      apiVersion: '0.2',
      id,
      name,
      kind: 'value-lattice',
      entry: './domain.mjs',
      languages: ['c', 'llvm-ir'],
    },
    null,
    2
  )}\n`;
}
