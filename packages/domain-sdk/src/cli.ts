#!/usr/bin/env node
import { mkdir, writeFile } from 'node:fs/promises';
import * as path from 'node:path';
import { DOMAINS } from '@aiviz/analysis-core';
import {
  DOMAIN_API_VERSION,
  DOMAIN_MANIFEST_SCHEMA_VERSION,
  validateWorkspaceDomain,
} from './workspaceDomains.js';

interface CreateArgs {
  directory?: string;
  id?: string;
  name?: string;
  languages: string[];
}

const domainIdPattern = /^[a-z][a-z0-9-]*$/;

function usage(): string {
  return `aiviz-domain — create and validate AIViz workspace value domains

Usage:
  aiviz-domain create <directory> --id <domain-id> --name <display name> [--languages c,llvm-ir]
  aiviz-domain check <directory>

Examples:
  aiviz-domain create .aiviz/domains/zero-nonzero --id zero-nonzero --name "Zero / Nonzero"
  aiviz-domain check .aiviz/domains/zero-nonzero
`;
}

function createTemplate(id: string, name: string): string {
  return `// Generated by aiviz-domain. Replace the conservative operations with your domain semantics.
const BOT = 0;
const ZERO = 1;
const NONZERO = 2;
const TOP = ZERO | NONZERO;

export const lattice = {
  id: ${JSON.stringify(id)},
  name: ${JSON.stringify(name)},
  finiteLattice: true,
  bottom: BOT,
  top: TOP,
  isBottom: (value) => value === BOT,
  isTop: (value) => value === TOP,
  equal: (left, right) => left === right,
  leq: (left, right) => (left & ~right) === 0,
  join: (left, right) => left | right,
  meet: (left, right) => left & right,
  widen: (left, right) => left | right,
  narrow: (left, right) => left & right,
  constant: (value) => (value === 0 ? ZERO : NONZERO),
  add: (_left, _right) => TOP,
  sub: (_left, _right) => TOP,
  mul: (_left, _right) => TOP,
  div: (_left, _right) => TOP,
  mod: (_left, _right) => TOP,
  neg: (value) => value,
  refine: (_operator, left, _right) => left,
  format: (value) =>
    value === BOT
      ? { repr: '⊥', kind: 'bottom' }
      : value === TOP
        ? { repr: '⊤', kind: 'top' }
        : { repr: value === ZERO ? '0' : '≠0', kind: 'value' },
  describeLoss: () => undefined,
  latticeGraph: () => ({
    nodes: [
      { id: 'bottom', label: '⊥' },
      { id: 'zero', label: '0' },
      { id: 'nonzero', label: '≠0' },
      { id: 'top', label: '⊤' },
    ],
    edges: [
      ['bottom', 'zero'],
      ['bottom', 'nonzero'],
      ['zero', 'top'],
      ['nonzero', 'top'],
    ],
  }),
};
`;
}

function parseCreate(args: string[]): CreateArgs | string {
  const out: CreateArgs = { languages: ['c', 'llvm-ir'] };
  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    if (!arg) continue;
    if (!arg.startsWith('--') && !out.directory) {
      out.directory = arg;
      continue;
    }
    const value = args[++index];
    if (!value) return `missing value for ${arg}`;
    if (arg === '--id') out.id = value;
    else if (arg === '--name') out.name = value;
    else if (arg === '--languages') out.languages = value.split(',').map((item) => item.trim());
    else return `unknown option ${arg}`;
  }
  if (!out.directory || !out.id || !out.name) {
    return 'create requires <directory>, --id, and --name';
  }
  if (!domainIdPattern.test(out.id)) return 'id must match ^[a-z][a-z0-9-]*$';
  if (out.name.trim().length === 0) return 'name must not be blank';
  if (
    out.languages.length === 0 ||
    out.languages.some((language) => language.length === 0) ||
    new Set(out.languages).size !== out.languages.length
  ) {
    return 'languages must be a non-empty comma-separated list without duplicates';
  }
  if (DOMAINS.some((domain) => domain.id === out.id)) {
    return `id "${out.id}" is reserved by a built-in domain`;
  }
  return out;
}

async function create(args: string[]): Promise<number> {
  const parsed = parseCreate(args);
  if (typeof parsed === 'string') {
    process.stderr.write(`aiviz-domain: ${parsed}\n`);
    return 2;
  }
  // parseCreate guarantees these, but retain an explicit guard for TypeScript
  // and for future callers constructing CreateArgs directly.
  if (!parsed.directory || !parsed.id || !parsed.name) {
    process.stderr.write('aiviz-domain: create requires <directory>, --id, and --name\n');
    return 2;
  }
  const manifest = {
    schemaVersion: DOMAIN_MANIFEST_SCHEMA_VERSION,
    apiVersion: DOMAIN_API_VERSION,
    id: parsed.id,
    name: parsed.name,
    kind: 'value-lattice',
    entry: './domain.mjs',
    languages: parsed.languages,
  };
  const target = path.resolve(parsed.directory);
  try {
    await mkdir(path.dirname(target), { recursive: true });
    await mkdir(target);
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (code === 'ENOENT') {
      process.stderr.write(
        `aiviz-domain: parent directory does not exist: ${path.dirname(target)}\n`
      );
    } else if (code === 'EEXIST') {
      process.stderr.write(`aiviz-domain: directory already exists: ${target}\n`);
    } else {
      process.stderr.write(`aiviz-domain: cannot create directory: ${String(error)}\n`);
    }
    return 1;
  }
  await writeFile(path.join(target, 'domain.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(path.join(target, 'domain.mjs'), createTemplate(parsed.id, parsed.name));
  process.stdout.write(`created ${target}\nrun: aiviz-domain check ${target}\n`);
  return 0;
}

async function check(directory: string | undefined): Promise<number> {
  if (!directory) {
    process.stderr.write('aiviz-domain: check requires <directory>\n');
    return 2;
  }
  const result = await validateWorkspaceDomain(path.resolve(directory), DOMAINS.map((domain) => domain.id));
  for (const diagnostic of result.diagnostics) {
    process.stderr.write(
      `${diagnostic.severity} ${diagnostic.code}: ${diagnostic.message}` +
        (diagnostic.path ? ` (${diagnostic.path})` : '') +
        '\n'
    );
  }
  if (result.diagnostics.some((diagnostic) => diagnostic.severity === 'error')) return 1;
  if (!result.manifest || !result.domain) {
    process.stderr.write('aiviz-domain: validation produced no loadable domain\n');
    return 1;
  }
  process.stdout.write(
    `ok ${result.manifest.id} — ${result.manifest.name} (${result.manifest.languages.join(', ')})\n`
  );
  return 0;
}

async function main(): Promise<number> {
  const [command, ...args] = process.argv.slice(2);
  if (!command || command === '--help' || command === '-h' || command === 'help') {
    process.stdout.write(usage());
    return command ? 0 : 2;
  }
  if (command === 'create') return create(args);
  if (command === 'check') return check(args[0]);
  process.stderr.write(`aiviz-domain: unknown command ${command}\n${usage()}`);
  return 2;
}

main()
  .then((code) => {
    process.exitCode = code;
  })
  .catch((error) => {
    process.stderr.write(`aiviz-domain: ${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
